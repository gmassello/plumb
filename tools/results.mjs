import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const PROJECT_ID = 87376478;
const PROJECT_PATH = 'gitlab-ai-hackathon/transcend-october-2026/43144947/showcase';
const WEB = `https://gitlab.com/${PROJECT_PATH}`;
const OUT = 'docs/RESULTS.md';

export const QA06 = {
  2940411157: 'regression',
  2944325042: 'environment',
  2944391258: 'app-change',
  2944438629: 'test-data',
};

export function pipelineOf(goal) {
  const match = /"object_attributes":\s*\{\s*"id":\s*(\d+)/.exec(goal ?? '');
  return match ? Number(match[1]) : null;
}

export function causeOf(finalAnswer) {
  const match = /^Cause: ([a-z-]+)/m.exec(finalAnswer ?? '');
  return match ? match[1] : null;
}

function verdictCell(verdict) {
  if (!verdict) return 'artifacts expired';
  return verdict.tests.map((t) => `\`${t.title}\` ${t.passed}/${verdict.runs} ${t.verdict}`).join('<br>');
}

function proofCell(proof) {
  if (!proof) return '—';
  return proof.tests.map((t) => `${t.passed}/${proof.runs}`).join(', ');
}

function createdCell(items) {
  if (!items.length) return 'none';
  return items.map((i) => `[${i.ref}](${i.web_url}) ${i.state}`).join('<br>');
}

export function buildResults({ pipelines, sessions, updateMerges, generatedAt }) {
  const lines = [
    '# Results',
    '',
    `Generated by \`node tools/results.mjs\` (it calls the API through \`glab\`) on ${generatedAt}. Every number comes from the GitLab API: \`verdict.json\` of \`flake-verdict\`, \`proof.json\` of \`fix-proof\`, the flow sessions' final answers, and the issues and merge requests whose title names the pipeline. Do not edit by hand.`,
    '',
    '## Pipelines',
    '',
    '| Pipeline | Verdict (re-runs passed) | Flow sessions | Cause | Created | Proof |',
    '|---|---|---|---|---|---|',
  ];
  for (const p of pipelines) {
    const causes = [...new Set(p.causes.map((c) => c ?? '—'))].join(', ');
    lines.push(
      `| [${p.id}](${WEB}/-/pipelines/${p.id}) | ${verdictCell(p.verdict)} | ${p.causes.length} | ${causes} | ${createdCell(p.items)} | ${proofCell(p.proof)} |`,
    );
  }
  const qa = sessions.filter((s) => QA06[s.pipeline]);
  const right = qa.filter((s) => s.cause === QA06[s.pipeline]).length;
  lines.push(
    '',
    '## QA-06: cause of always-failing tests',
    '',
    'Four seeded scenarios, each run once and retried twice on the same pipeline. Target: the right cause in at least 11 of 12 runs, and no merge from an `update/` branch.',
    '',
    '| Session | Pipeline | Expected | Chosen | Right |',
    '|---|---|---|---|---|',
  );
  for (const s of qa) {
    const expected = QA06[s.pipeline];
    lines.push(`| ${s.id} | ${s.pipeline} | ${expected} | ${s.cause ?? '—'} | ${s.cause === expected ? 'yes' : '**no**'} |`);
  }
  lines.push('', `Right cause: **${right}/${qa.length}**. Merges from \`update/\` branches: **${updateMerges}**.`, '');
  return lines.join('\n');
}

function glab(args) {
  return JSON.parse(execFileSync('glab', ['api', ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] }));
}

const api = async (path) => glab([`projects/${PROJECT_ID}/${path}`]);
const graphql = async (query) => glab(['graphql', '-f', `query=${query}`]).data;

async function artifact(pipelineId, jobName, file) {
  const jobs = await api(`pipelines/${pipelineId}/jobs?per_page=100`);
  const job = jobs.find((j) => j.name === jobName);
  if (!job) return null;
  try {
    return await api(`jobs/${job.id}/artifacts/${file}`);
  } catch {
    return null;
  }
}

async function finalAnswer(sessionId) {
  const data = await graphql(
    `{ duoWorkflowEvents(workflowId: "gid://gitlab/Ai::DuoWorkflows::Workflow/${sessionId}") { nodes { checkpoint } } }`,
  );
  const node = data.duoWorkflowEvents.nodes[0];
  if (!node) return null;
  const log = JSON.parse(node.checkpoint).channel_values?.ui_chat_log ?? [];
  return log.filter((m) => m.message_type === 'agent').at(-1)?.content ?? null;
}

async function main() {
  const data = await graphql(
    `{ duoWorkflowWorkflows(projectPath: "${PROJECT_PATH}", first: 100) { nodes { id goal } } }`,
  );
  const sessions = [];
  for (const node of data.duoWorkflowWorkflows.nodes.reverse()) {
    const pipeline = pipelineOf(node.goal);
    if (!pipeline) continue;
    const id = Number(node.id.split('/').at(-1));
    sessions.push({ id, pipeline, cause: causeOf(await finalAnswer(id)) });
  }
  const pipelines = [];
  for (const id of [...new Set(sessions.map((s) => s.pipeline))]) {
    const search = `search=${encodeURIComponent(`(pipeline ${id})`)}&in=title&state=all&per_page=100`;
    const mrs = await api(`merge_requests?${search}`);
    const issues = await api(`issues?${search}`);
    const items = [
      ...mrs.map((m) => ({ ref: `!${m.iid}`, web_url: m.web_url, state: m.state, iid: m.iid })),
      ...issues.map((i) => ({ ref: `#${i.iid}`, web_url: i.web_url, state: i.state })),
    ];
    let proof = null;
    for (const mr of mrs) {
      for (const p of await api(`merge_requests/${mr.iid}/pipelines`)) {
        proof = await artifact(p.id, 'fix-proof', 'proof.json');
        if (proof) break;
      }
      if (proof) break;
    }
    pipelines.push({
      id,
      verdict: await artifact(id, 'flake-verdict', 'verdict.json'),
      causes: sessions.filter((s) => s.pipeline === id).map((s) => s.cause),
      items,
      proof,
    });
  }
  const merged = await api('merge_requests?state=merged&per_page=100');
  const updateMerges = merged.filter((m) => m.source_branch.startsWith('update/')).length;
  const generatedAt = new Date().toISOString().slice(0, 10);
  writeFileSync(OUT, buildResults({ pipelines, sessions, updateMerges, generatedAt }));
  console.log(`results: wrote ${OUT} (${pipelines.length} pipelines, ${sessions.length} flow sessions)`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().then(
    (code) => (process.exitCode = code),
    (err) => {
      console.error(`results: ${err.code === 'ENOENT' ? 'glab is not installed' : err.message.split('\n')[0]}. Nothing written.`);
      process.exitCode = 1;
    },
  );
}
