import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { rate } from './summary.mjs';

export function options(args) {
  const { values } = parseArgs({
    args,
    options: {
      project: { type: 'string', default: '87376478' },
      path: { type: 'string', default: 'gitlab-ai-hackathon/transcend-october-2026/43144947/showcase' },
      out: { type: 'string', default: 'docs/RESULTS.md' },
    },
  });
  return { ...values, sessions: join(dirname(values.out), 'sessions'), web: `https://gitlab.com/${values.path}` };
}

let opts = options([]);
let WEB = opts.web;

export const QA06 = {
  2940411157: 'regression',
  2944325042: 'environment',
  2944391258: 'app-change',
  2944438629: 'test-data',
};

export function pipelineOf(goal) {
  const match = /"object_attributes":\s*\{\s*"id":\s*(\d+)/.exec(goal ?? '');
  return match ? Number(match[1]) : null;
}

export function causeOf(finalAnswer) {
  const match = /^Cause: ([a-z-]+)/m.exec(finalAnswer ?? '');
  return match ? match[1] : null;
}

const cell = (text, max) => {
  const flat = String(text ?? '').replace(/\s+/g, ' ').trim().replace(/\|/g, '\\|');
  return flat.length > max ? `${flat.slice(0, max)}…` : flat;
};

export function transcript({ id, pipeline }, log) {
  const lines = [
    `# Flow session ${id}`,
    '',
    `Pipeline [${pipeline}](${WEB}/-/pipelines/${pipeline}). Exported by \`node tools/results.mjs\` from the session's \`ui_chat_log\`; tool responses are left out.`,
    '',
    '| UTC | Step | Detail |',
    '|---|---|---|',
  ];
  const answers = [];
  for (const m of log) {
    const time = (m.timestamp ?? '').slice(11, 19);
    if (m.message_type === 'agent') {
      answers.push(m.content ?? '');
      lines.push(`| ${time} | final answer | see below |`);
      continue;
    }
    const step = m.message_sub_type && m.message_sub_type !== 'None' ? m.message_sub_type : m.message_type;
    lines.push(`| ${time} | ${step}${m.status && m.status !== 'success' ? ` (${m.status})` : ''} | ${cell(m.content, 240)} |`);
  }
  lines.push('', '## Final answer', '', ...(answers.length ? answers.at(-1).split('\n').map((l) => `> ${l}`) : ['none']), '');
  return lines.join('\n');
}

function verdictCell(verdict) {
  if (!verdict) return 'artifacts expired';
  if (verdict.infra) return `infra: ${verdict.infra.pattern}`;
  return verdict.tests.map((t) => `\`${t.title}\` ${rate(t)} ${t.verdict}`).join('<br>');
}

function proofCell(proof) {
  if (!proof) return '—';
  return proof.tests.map(rate).join(', ');
}

export const minutes = (jobs) => Math.round(jobs.reduce((sum, j) => sum + (j.duration ?? 0), 0) / 6) / 10;

export function median(values) {
  const v = [...values].sort((a, b) => a - b);
  if (!v.length) return null;
  const mid = Math.floor(v.length / 2);
  return v.length % 2 ? v[mid] : Math.round(((v[mid - 1] + v[mid]) / 2) * 10) / 10;
}

export function mergeCell(items) {
  const merged = items.filter((i) => i.ref.startsWith('!') && i.state === 'merged');
  if (!merged.length) return '—';
  return merged.map((m) => (m.mergeGate ? `${m.ref} by [\`merge-gate\`](${WEB}/-/jobs/${m.mergeGate})` : `${m.ref} by hand`)).join('<br>');
}

function ciCell(ci) {
  return ci ? `${ci.red} + ${ci.mr}` : '—';
}

function createdCell(items) {
  if (!items.length) return 'none';
  return items.map((i) => `[${i.ref}](${i.web_url}) ${i.state}`).join('<br>');
}

export function buildResults({ pipelines, sessions, updateMerges, generatedAt }) {
  const lines = [
    '# Results',
    '',
    `Generated by \`node tools/results.mjs\` (it calls the API through \`glab\`) on ${generatedAt}. Every number comes from the GitLab API: \`verdict.json\` of \`flake-verdict\`, \`proof.json\` of \`fix-proof\`, the flow sessions' final answers, and the issues and merge requests whose title names the pipeline. Do not edit by hand.`,
    '',
    '## Pipelines',
    '',
    '| Pipeline | Verdict (re-runs passed) | Flow sessions (transcripts) | Cause | Created | Proof | Merge | CI minutes (red + MR pipeline) |',
    '|---|---|---|---|---|---|---|---|',
  ];
  for (const p of pipelines) {
    const causes = [...new Set(p.causes.map((c) => c ?? '—'))].join(', ');
    const runs = p.sessions?.length ? p.sessions.map((id) => `[${id}](sessions/${id}.md)`).join('<br>') : p.causes.length;
    lines.push(
      `| [${p.id}](${WEB}/-/pipelines/${p.id}) | ${verdictCell(p.verdict)} | ${runs} | ${causes} | ${createdCell(p.items)} | ${proofCell(p.proof)} | ${mergeCell(p.items)} | ${ciCell(p.ci)} |`,
    );
  }
  const costs = pipelines.filter((p) => p.ci).map((p) => Math.round((p.ci.red + p.ci.mr) * 10) / 10);
  if (costs.length) {
    lines.push(
      '',
      `CI minutes are the sum of every job's duration in the red pipeline and in the merge request pipeline that ran the proof. Over the ${costs.length} incidents with a fix merge request: median **${median(costs)} min**, total **${Math.round(costs.reduce((a, b) => a + b, 0) * 10) / 10} min**. A merge marked \`merge-gate\` was made by that CI job (its log shows the API call); GitLab names the token's owner in the merge note because \`MERGE_BOT_TOKEN\` is the author's personal access token.`,
    );
  }
  const qa = sessions.filter((s) => QA06[s.pipeline]);
  if (!qa.length) return [...lines, ''].join('\n');
  const right = qa.filter((s) => s.cause === QA06[s.pipeline]).length;
  lines.push(
    '',
    '## QA-06: cause of always-failing tests',
    '',
    'Four seeded scenarios, each run once and retried twice on the same pipeline. Target: the right cause in at least 11 of 12 runs, and no merge from an `update/` branch.',
    '',
    '| Session | Pipeline | Expected | Chosen | Right |',
    '|---|---|---|---|---|',
  );
  for (const s of qa) {
    const expected = QA06[s.pipeline];
    lines.push(`| ${s.id} | ${s.pipeline} | ${expected} | ${s.cause ?? '—'} | ${s.cause === expected ? 'yes' : '**no**'} |`);
  }
  lines.push('', `Right cause: **${right}/${qa.length}**. Merges from \`update/\` branches: **${updateMerges}**.`, '');
  return lines.join('\n');
}

function glab(args) {
  return JSON.parse(execFileSync('glab', ['api', ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] }));
}

const api = async (path) => glab([`projects/${opts.project}/${path}`]);
const graphql = async (query) => glab(['graphql', '-f', `query=${query}`]).data;

const jobCache = new Map();
async function jobsOf(pipelineId) {
  if (!jobCache.has(pipelineId)) jobCache.set(pipelineId, await api(`pipelines/${pipelineId}/jobs?per_page=100`));
  return jobCache.get(pipelineId);
}

async function artifact(pipelineId, jobName, file) {
  const jobs = await jobsOf(pipelineId);
  const job = jobs.find((j) => j.name === jobName);
  if (!job) return null;
  try {
    return await api(`jobs/${job.id}/artifacts/${file}`);
  } catch {
    return null;
  }
}

async function chatLog(sessionId) {
  const data = await graphql(
    `{ duoWorkflowEvents(workflowId: "gid://gitlab/Ai::DuoWorkflows::Workflow/${sessionId}") { nodes { checkpoint } } }`,
  );
  const node = data.duoWorkflowEvents.nodes[0];
  return node ? JSON.parse(node.checkpoint).channel_values?.ui_chat_log ?? [] : [];
}

async function main() {
  opts = options(process.argv.slice(2));
  WEB = opts.web;
  const data = await graphql(
    `{ duoWorkflowWorkflows(projectPath: "${opts.path}", first: 100) { nodes { id goal } } }`,
  );
  const sessions = [];
  mkdirSync(opts.sessions, { recursive: true });
  for (const node of data.duoWorkflowWorkflows.nodes.reverse()) {
    const pipeline = pipelineOf(node.goal);
    if (!pipeline) continue;
    const id = Number(node.id.split('/').at(-1));
    const log = await chatLog(id);
    writeFileSync(`${opts.sessions}/${id}.md`, transcript({ id, pipeline }, log));
    sessions.push({ id, pipeline, cause: causeOf(log.filter((m) => m.message_type === 'agent').at(-1)?.content) });
  }
  const pipelines = [];
  for (const id of [...new Set(sessions.map((s) => s.pipeline))]) {
    const search = `search=${encodeURIComponent(`(pipeline ${id})`)}&in=title&state=all&per_page=100`;
    const mrs = await api(`merge_requests?${search}`);
    const issues = await api(`issues?${search}`);
    const items = [
      ...mrs.map((m) => ({ ref: `!${m.iid}`, web_url: m.web_url, state: m.state, iid: m.iid })),
      ...issues.map((i) => ({ ref: `#${i.iid}`, web_url: i.web_url, state: i.state })),
    ];
    let proof = null;
    let proofPipeline = null;
    for (const mr of mrs) {
      for (const p of (await api(`merge_requests/${mr.iid}/pipelines`)).reverse()) {
        const gate = (await jobsOf(p.id)).find((j) => j.name === 'merge-gate' && j.status === 'success');
        const item = items.find((i) => i.iid === mr.iid);
        if (gate && !item.mergeGate) item.mergeGate = gate.id;
        if (!proof) {
          proof = await artifact(p.id, 'fix-proof', 'proof.json');
          if (proof) proofPipeline = p.id;
        }
      }
    }
    const ci = proofPipeline ? { red: minutes(await jobsOf(id)), mr: minutes(await jobsOf(proofPipeline)) } : null;
    pipelines.push({
      id,
      verdict: await artifact(id, 'flake-verdict', 'verdict.json'),
      causes: sessions.filter((s) => s.pipeline === id).map((s) => s.cause),
      sessions: sessions.filter((s) => s.pipeline === id).map((s) => s.id),
      items,
      proof,
      ci,
    });
  }
  const merged = await api('merge_requests?state=merged&per_page=100');
  const updateMerges = merged.filter((m) => m.source_branch.startsWith('update/')).length;
  const generatedAt = new Date().toISOString().slice(0, 10);
  writeFileSync(opts.out, buildResults({ pipelines, sessions, updateMerges, generatedAt }));
  console.log(`results: wrote ${opts.out} (${pipelines.length} pipelines, ${sessions.length} flow sessions)`);
  return 0;
}

